import static java.lang.Math.*;

public class StaticImportDemo {
    public static void main(String[] args) {
        System.out.println("sqrt(144)  = " + sqrt(144));
        System.out.println("pow(2, 10) = " + pow(2, 10));
        System.out.println("max(78,95) = " + max(78, 95));
        System.out.println("min(78,95) = " + min(78, 95));
        System.out.println("abs(-37.5) = " + abs(-37.5));
        System.out.println("ceil(4.3)  = " + ceil(4.3));
        System.out.println("floor(4.9) = " + floor(4.9));
        System.out.println("round(4.6) = " + round(4.6));
        System.out.println("PI         = " + PI);
    }
}
